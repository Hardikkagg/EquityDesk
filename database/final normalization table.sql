SELECT
    c.TABLE_NAME,
    c.COLUMN_NAME,
    c.COLUMN_TYPE,
    CASE
        WHEN c.COLUMN_KEY = 'PRI' THEN 'YES'
        ELSE 'NO'
    END AS PRIMARY_KEY,
    k.REFERENCED_TABLE_NAME AS FOREIGN_KEY_TABLE,
    k.REFERENCED_COLUMN_NAME AS FOREIGN_KEY_COLUMN

FROM INFORMATION_SCHEMA.COLUMNS c

LEFT JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE k
    ON c.TABLE_SCHEMA = k.TABLE_SCHEMA
    AND c.TABLE_NAME = k.TABLE_NAME
    AND c.COLUMN_NAME = k.COLUMN_NAME
    AND k.REFERENCED_TABLE_NAME IS NOT NULL

WHERE c.TABLE_SCHEMA = DATABASE()
AND c.TABLE_NAME IN (
    'INVESTOR_3NF',
    'PORTFOLIO_3NF',
    'SECURITY_3NF',
    'PORTFOLIO_POSITION_3NF',
    'TRADE_3NF'
)

ORDER BY
    FIELD(
        c.TABLE_NAME,
        'INVESTOR_3NF',
        'PORTFOLIO_3NF',
        'SECURITY_3NF',
        'PORTFOLIO_POSITION_3NF',
        'TRADE_3NF'
    ),
    c.ORDINAL_POSITION;
    
    
SELECT * FROM INVESTOR_3NF;
SELECT * FROM PORTFOLIO_3NF;
SELECT * FROM SECURITY_3NF;
SELECT * FROM PORTFOLIO_POSITION_3NF;
SELECT * FROM TRADE_3NF;